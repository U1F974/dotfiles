#!/usr/bin/env python3
"""Generate shell theme CSS that replaces the system accent color with ACCENT.

GNOME Shell takes the accent from the Settings choice (blue, teal, green, ...)
and passes it to the theme as -st-accent-color; a theme cannot redefine that
value, and St has no API to set it. Instead, this script copies every
declaration that uses -st-accent-color from the built-in dark shell theme,
keeps the selectors and their order, and puts ACCENT in its place. MyShell
imports the result after the built-in theme. Run it again after GNOME Shell
updates.

GTK 4 apps get the same color from --accent-bg-color in
home/.config/gtk-4.0/gtk.css: keep the two in sync.

Usage: tools/gen-accent.py      # writes home/.local/share/themes/MyShell/
                                 # gnome-shell/accent.css in the repo
                                 # (installed as a symlink)
"""

import re
import subprocess
from pathlib import Path

ACCENT = '#478061'                 # green of the Void Linux logo
REPO = Path(__file__).resolve().parent.parent
SOURCE = ('/usr/share/gnome-shell/gnome-shell-theme.gresource',
          '/org/gnome/shell/theme/gnome-shell-dark.css')
TARGET = REPO / 'home' / '.local' / 'share' / 'themes' / 'MyShell' / 'gnome-shell' / 'accent.css'

# The shell CSS is flat: no @media or other blocks with nested rules.
RULE = re.compile(r'([^{}]+)\{([^{}]*)\}')


def extract(resource, path):
    return subprocess.run(['gresource', 'extract', resource, path],
                          check=True, capture_output=True, text=True).stdout


def generate(css):
    out = ['/* Generated by gen-accent.py from built-in GNOME Shell theme CSS.',
           '   Do not edit by hand: change the script and run it again. */', '']
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    for selector, body in RULE.findall(css):
        # Only declarations with the accent itself: -st-accent-fg-color
        # (text on the accent) stays the system one, white for every accent.
        decls = [' '.join(d.split()) for d in body.split(';') if '-st-accent-color' in d]
        if not decls:
            continue
        lines = [f'  {d.replace("-st-accent-color", ACCENT)};' for d in decls]
        selectors = ',\n'.join(' '.join(s.split()) for s in selector.split(','))
        out.append(selectors + ' {\n' + '\n'.join(lines) + '\n}')
    return '\n'.join(out) + '\n'


def main():
    TARGET.write_text(generate(extract(*SOURCE)))
    print('wrote', TARGET)


if __name__ == '__main__':
    main()
