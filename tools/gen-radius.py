#!/usr/bin/env python3
"""Generate GTK user CSS that makes corner radii match the shell theme (3px).

User CSS (~/.config/gtk-*/gtk.css) has higher priority than the theme, so a
plain `button { border-radius: 3px }` would also beat the theme rules that
zero corners inside linked groups, keep circular buttons round, etc. Instead,
this script copies every radius rule from the built-in theme CSS, keeps the
selectors and their order, and only rewrites the values. Run it again after
libadwaita or GTK updates.

Usage: tools/gen-radius.py      # writes home/.config/gtk-{3,4}.0/radius.css
                                 # in the repo (installed as symlinks)
"""

import re
import subprocess
from pathlib import Path

RADIUS = '3px'
REPO = Path(__file__).resolve().parent.parent

SOURCES = {
    '4.0': ('/usr/lib/libadwaita-1.so.0', '/org/gnome/Adwaita/styles/gtk.css'),
    '3.0': ('/usr/lib/libgtk-3.so.0', '/org/gtk/libgtk/theme/Adwaita/gtk-contained-dark.css'),
}

# Shapes that stay as they are: switches, sliders, bars, avatars, radio
# buttons, dots and handles are round by design.
KEEP = re.compile(r'\bswitch\b|\bscale\b(?!-)|progressbar|levelbar|scrollbar|avatar|'
                  r'\bradio\b|slider|cursor-handle|drag-handle|indicator|colorswatch')

# Pill shapes (radius >= 99px) that become plain 3px rectangles.
PILLS = re.compile(r'\.pill\b|\btoast\b|app-version|toggle-group\.round|'
                   r'dialog\.shortcuts \.navigation-box > button')

DECL = re.compile(r'(border(?:-(?:top|bottom)-(?:left|right))?-radius)\s*:\s*([^;]+)')


def extract(lib, path):
    return subprocess.run(['gresource', 'extract', lib, path],
                          check=True, capture_output=True, text=True).stdout


def top_level_rules(css):
    """Yield (selector, body) for rules outside @media and other at-rules."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    depth, start, in_at = 0, 0, False
    for i, ch in enumerate(css):
        if ch == '{':
            if depth == 0:
                selector = css[start:i].strip()
                in_at = selector.startswith('@')
                sel_start, body_start = selector, i + 1
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                if not in_at:
                    yield sel_start, css[body_start:i]
                start = i + 1
        elif ch == ';' and depth == 0:
            start = i + 1


def map_value(token, selector):
    if token.startswith('calc('):
        return '1px'                       # inner toggle of a toggle group
    if token.startswith('var(') or token.endswith('%') or token in ('0', '0px'):
        return token
    m = re.fullmatch(r'([\d.]+)px', token)
    if not m:
        return token
    px = float(m.group(1))
    if px >= 99:
        return RADIUS if PILLS.search(selector) else token
    if px <= 3 or KEEP.search(selector):
        return token
    return RADIUS


def split_tokens(value):
    """Split a radius value on spaces, keeping calc()/var() intact."""
    tokens, depth, cur = [], 0, ''
    for ch in value:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ' ' and depth == 0:
            if cur:
                tokens.append(cur)
            cur = ''
        else:
            cur += ch
    if cur:
        tokens.append(cur)
    return tokens


def generate(css, version):
    out = [f'/* Generated by gen-radius.py from built-in GTK {version} theme CSS.',
           f'   Do not edit by hand: change the script and run it again. */', '']
    if version == '4.0':
        out += [f':root {{ --window-radius: {RADIUS}; }}', '']
    for selector, body in top_level_rules(css):
        decls = DECL.findall(body)
        if not decls:
            continue
        # One rule per selector: KEEP/PILLS must decide for each selector of
        # a group separately (the theme groups e.g. `button` with colorswatch).
        for sel in selector.split(','):
            sel = ' '.join(sel.split())
            lines = []
            for prop, value in decls:
                value = value.replace('!important', '').strip()
                new = ' '.join(map_value(t, sel) for t in split_tokens(value))
                lines.append(f'  {prop}: {new};')
            out.append(sel + ' {\n' + '\n'.join(lines) + '\n}')
    return '\n'.join(out) + '\n'


def main():
    for version, (lib, path) in SOURCES.items():
        target = REPO / 'home' / '.config' / f'gtk-{version}' / 'radius.css'
        target.write_text(generate(extract(lib, path), version))
        print('wrote', target)


if __name__ == '__main__':
    main()
